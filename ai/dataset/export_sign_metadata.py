"""Regenerate every copy of the per-sign metadata from ai/dataset/sign_metadata.json.

sign_metadata.json is the single source of truth for each sign's gloss,
English/Filipino meaning, synonyms, sign type (static/dynamic), hands
(one/two), reference-video source and validation status. This script writes:

  android/SignTalk/app/src/main/java/com/example/signtalk/data/dictionary/SignMetadata.kt
  backend/sign-talk-api/src/scripts/signMetadata.json
  docs/sign_table.md   (the "all 50 signs" table for the manuscript)

Run from the repo root:  python ai/dataset/export_sign_metadata.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
META = ROOT / "ai" / "dataset" / "sign_metadata.json"
LABELS = ROOT / "android" / "SignTalk" / "app" / "src" / "main" / "assets" / "labels.json"
BACKEND_DATA = ROOT / "backend" / "sign-talk-api" / "src" / "scripts" / "dictionaryData.js"
KOTLIN_OUT = ROOT / "android" / "SignTalk" / "app" / "src" / "main" / "java" / "com" / "example" / "signtalk" / "data" / "dictionary" / "SignMetadata.kt"
BACKEND_OUT = ROOT / "backend" / "sign-talk-api" / "src" / "scripts" / "signMetadata.json"
TABLE_OUT = ROOT / "docs" / "sign_table.md"


def kt(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main() -> None:
    signs = json.loads(META.read_text(encoding="utf-8"))["signs"]
    labels = json.loads(LABELS.read_text(encoding="utf-8"))["labels"]
    order = [l["label"] for l in labels]
    if [s["slug"] for s in signs] != order:
        raise SystemExit("sign_metadata.json order/slugs must match assets/labels.json exactly")
    display = {l["label"]: l["displayName"] for l in labels}
    categories = dict(re.findall(r'slug: "([^"]+)".*?category: "([^"]+)"', BACKEND_DATA.read_text(encoding="utf-8")))

    # ---- Kotlin ----
    lines = [
        "package com.example.signtalk.data.dictionary",
        "",
        "// GENERATED by ai/dataset/export_sign_metadata.py from ai/dataset/sign_metadata.json.",
        "// Do not edit by hand: change the JSON and re-run the script.",
        "",
        "/** Linguistic and provenance metadata for one bundled sign (see [signMetadata]). */",
        "data class SignMeta(",
        "    val language: String,",
        "    val gloss: String,",
        "    val meaningEn: String,",
        "    val meaningFil: String,",
        "    val synonyms: List<String>,",
        "    val signType: String,",
        "    val hands: String,",
        "    val source: String,",
        "    val validationStatus: String,",
        "    val validatedBy: String",
        ")",
        "",
        "val signMetadata: Map<String, SignMeta> = mapOf(",
    ]
    for s in signs:
        syn = ", ".join(kt(x) for x in s["synonyms"])
        lines.append(
            f"    {kt(s['slug'])} to SignMeta({kt(s['language'])}, {kt(s['gloss'])}, {kt(s['meaningEn'])}, {kt(s['meaningFil'])}, "
            f"listOf({syn}), {kt(s['signType'])}, {kt(s['hands'])}, {kt(s['source'])}, "
            f"{kt(s['validationStatus'])}, {kt(s.get('validatedBy', ''))}),"
        )
    lines[-1] = lines[-1].rstrip(",")
    lines += [")", ""]
    KOTLIN_OUT.write_text("\n".join(lines), encoding="utf-8")

    # ---- Backend ----
    BACKEND_OUT.write_text(json.dumps(signs, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # ---- Manuscript table ----
    TABLE_OUT.parent.mkdir(parents=True, exist_ok=True)
    rows = [
        "# SignTalk: all 50 supported signs",
        "",
        "Generated from `ai/dataset/sign_metadata.json` by `ai/dataset/export_sign_metadata.py`.",
        "",
        "These are **50 distinct signs: 25 Filipino Sign Language (FSL) signs and 25 American Sign Language (ASL) signs.**",
        "They are not English and Filipino labels for the same 25 concepts. The three greetings exist in both languages as",
        "separate signs (for example FSL *Magandang Umaga* and ASL *Good Morning*), each with its own video and model class.",
        "",
        "Sign type and hands are the team's reading of the reference videos and are marked *unverified* until an FSL",
        "validator confirms them.",
        "",
        "| # | Sign (label) | Language | Category | Gloss | Meaning (English) | Meaning (Filipino) | Hands | Type | Reference video source | Validation |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for i, s in enumerate(signs, 1):
        cat = categories.get(s["slug"], "").split(" - ", 1)[-1]
        status = s["validationStatus"] + (f" ({s['validatedBy']})" if s.get("validatedBy") else "")
        rows.append(
            f"| {i} | {display[s['slug']]} (`{s['slug']}`) | {s['language']} | {cat} | {s['gloss']} | {s['meaningEn']} | "
            f"{s['meaningFil']} | {s['hands']} | {s['signType']} | {s['source']} | {status} |"
        )
    TABLE_OUT.write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"Wrote {KOTLIN_OUT.relative_to(ROOT)}, {BACKEND_OUT.relative_to(ROOT)}, {TABLE_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
