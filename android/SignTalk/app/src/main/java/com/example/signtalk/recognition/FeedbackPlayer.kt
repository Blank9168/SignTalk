package com.example.signtalk.recognition

import android.content.Context
import android.media.AudioManager
import android.media.ToneGenerator
import android.os.Build
import android.os.VibrationEffect
import android.os.Vibrator
import android.os.VibratorManager

/**
 * Non-speech feedback for recognition events. Every cue here is optional and always paired
 * with a visual state on screen (nothing is audio-only):
 *
 * - **Vibration** (on by default): one short pulse when a sign is accepted, a double pulse
 *   for "Not sure / Unknown". Useful for Deaf users, who won't hear a tone.
 * - **Sound effects** (off by default): short system tones from [ToneGenerator]. These are
 *   generated by Android itself, so there are no third-party audio files to license.
 *
 * There is no background music anywhere in the app, so nothing needs to be ducked while
 * text-to-speech is playing.
 */
class FeedbackPlayer(context: Context) {

    var vibrationEnabled = true
    var soundEffectsEnabled = false

    private val vibrator: Vibrator? =
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            (context.getSystemService(Context.VIBRATOR_MANAGER_SERVICE) as? VibratorManager)?.defaultVibrator
        } else {
            @Suppress("DEPRECATION")
            context.getSystemService(Context.VIBRATOR_SERVICE) as? Vibrator
        }

    private val tones: ToneGenerator? = try {
        ToneGenerator(AudioManager.STREAM_NOTIFICATION, 60)
    } catch (e: RuntimeException) {
        null // some devices refuse ToneGenerator; feedback is optional
    }

    fun success() {
        if (vibrationEnabled) vibrate(longArrayOf(0, 45))
        if (soundEffectsEnabled) tones?.startTone(ToneGenerator.TONE_PROP_ACK, 120)
    }

    fun warning() {
        if (vibrationEnabled) vibrate(longArrayOf(0, 35, 90, 35))
        if (soundEffectsEnabled) tones?.startTone(ToneGenerator.TONE_PROP_NACK, 150)
    }

    /** Light tick for button presses such as Try Again. */
    fun tap() {
        if (vibrationEnabled) vibrate(longArrayOf(0, 15))
    }

    private fun vibrate(pattern: LongArray) {
        val v = vibrator ?: return
        if (!v.hasVibrator()) return
        try {
            v.vibrate(VibrationEffect.createWaveform(pattern, -1))
        } catch (e: SecurityException) {
            // VIBRATE permission missing on a custom ROM: skip silently.
        }
    }

    fun release() {
        tones?.release()
    }
}
